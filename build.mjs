// Builds worker.js: src/worker.src.js with the browser module src/conflict-guard.js inserted.
// Usage: node build.mjs   (or npm run build)
import { readFileSync, writeFileSync } from "node:fs";

const PLACEHOLDER = "String.raw`__CONFLICT_GUARD_SOURCE__`";
const source = readFileSync(new URL("./src/worker.src.js", import.meta.url), "utf8");
const guard = readFileSync(new URL("./src/conflict-guard.js", import.meta.url), "utf8");

// The module is embedded in a String.raw template literal, so it must not contain these
if (guard.includes("`") || guard.includes("${")) {
  throw new Error("src/conflict-guard.js must not contain backticks or '${' (it is embedded in a template literal)");
}
if (source.split(PLACEHOLDER).length !== 2) {
  throw new Error(`src/worker.src.js must contain ${PLACEHOLDER} exactly once`);
}

const banner = "// GENERATED by build.mjs from src/worker.src.js and src/conflict-guard.js. Edit those, then run `npm run build`.\n";
writeFileSync(new URL("./worker.js", import.meta.url), banner + source.replace(PLACEHOLDER, "String.raw`" + guard + "`"));
console.log("worker.js written");
